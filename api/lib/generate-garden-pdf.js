import PDFDocument from "pdfkit";

const COLORS = {
  black: "#1a1a1a",
  darkGray: "#333333",
  gray: "#666666",
  lightGray: "#999999",
  border: "#e0e0e0",
  accent: "#16a34a",
  pageBg: "#ffffff",
};

function sanitizeText(text) {
  if (!text) return "";
  return String(text).replace(/[^\x00-\xFF]/g, "");
}

function drawFooter(doc, pageNum) {
  const y = doc.page.height - 50;
  const savedMargin = doc.page.margins.bottom;
  doc.page.margins.bottom = 0;

  doc
    .fontSize(7)
    .font("Helvetica")
    .fillColor(COLORS.lightGray)
    .text("Generated by VibeZap.dev - AI Land Design", 50, y, { continued: true })
    .text(`  |  Page ${pageNum}`, { align: "right" });

  doc.page.margins.bottom = savedMargin;
}

/**
 * Strip markdown to plain text (basic).
 */
function stripMd(md) {
  return sanitizeText(
    md
      .replace(/^#{1,4}\s+/gm, "")
      .replace(/\*\*([^*]+)\*\*/g, "$1")
      .replace(/\*([^*]+)\*/g, "$1")
      .replace(/~~([^~]+)~~/g, "$1")
      .replace(/\|/g, " | ")
  );
}

/**
 * Parse markdown into sections: { heading, body }[]
 */
function parseSections(md) {
  const sections = [];
  const lines = md.split("\n");
  let current = null;

  for (const line of lines) {
    const headingMatch = line.match(/^(#{2,3})\s+(.+)$/);
    if (headingMatch) {
      if (current) sections.push(current);
      current = { level: headingMatch[1].length, heading: headingMatch[2].trim(), body: "" };
    } else if (current) {
      current.body += line + "\n";
    } else {
      // Text before first heading
      if (!sections.length && line.trim()) {
        current = { level: 0, heading: "", body: line + "\n" };
      }
    }
  }
  if (current) sections.push(current);
  return sections;
}

export default async function generateGardenPdf({ reportMarkdown, location, siteData, sketchAnalysis, imageBase64 }) {
  return new Promise((resolve, reject) => {
    try {
      const doc = new PDFDocument({
        size: "A4",
        margins: { top: 60, bottom: 70, left: 50, right: 50 },
        bufferPages: true,
      });

      const chunks = [];
      doc.on("data", (chunk) => chunks.push(chunk));
      doc.on("end", () => resolve(Buffer.concat(chunks)));
      doc.on("error", reject);

      const pageWidth = doc.page.width - 100;

      // ── Title Page ──────────────────────────────────────────────────

      doc.moveDown(4);
      doc
        .font("Helvetica-Bold")
        .fontSize(28)
        .fillColor(COLORS.accent)
        .text(sanitizeText("Land Design Report"), { align: "center" });

      doc.moveDown(0.5);
      doc
        .font("Helvetica")
        .fontSize(12)
        .fillColor(COLORS.gray)
        .text(sanitizeText("AI-Powered Permaculture Design"), { align: "center" });

      doc.moveDown(2);

      // Location
      if (location?.displayName) {
        doc
          .font("Helvetica-Bold")
          .fontSize(11)
          .fillColor(COLORS.darkGray)
          .text(sanitizeText(location.displayName), { align: "center" });

        if (location.lat && location.lng) {
          doc
            .font("Helvetica")
            .fontSize(9)
            .fillColor(COLORS.lightGray)
            .text(`${location.lat.toFixed(4)}, ${location.lng.toFixed(4)}`, { align: "center" });
        }
      }

      doc.moveDown(1);

      // Site data summary
      if (siteData) {
        const summaryParts = [];
        if (siteData.koppen?.code) summaryParts.push(`Climate: ${siteData.koppen.code}`);
        if (siteData.elevation?.elevation != null) summaryParts.push(`Elevation: ${siteData.elevation.elevation}m`);
        if (siteData.climate?.annual?.rainfall != null) summaryParts.push(`Rainfall: ${siteData.climate.annual.rainfall}mm/yr`);
        if (siteData.frost?.frostRisk) summaryParts.push(`Frost: ${siteData.frost.frostRisk}`);
        if (siteData.soil?.textureClass) summaryParts.push(`Soil: ${siteData.soil.textureClass}`);

        if (summaryParts.length > 0) {
          doc
            .font("Helvetica")
            .fontSize(9)
            .fillColor(COLORS.gray)
            .text(sanitizeText(summaryParts.join("  |  ")), { align: "center" });
        }
      }

      doc.moveDown(1);

      // Divider
      doc
        .strokeColor(COLORS.border)
        .lineWidth(0.5)
        .moveTo(50, doc.y)
        .lineTo(50 + pageWidth, doc.y)
        .stroke();

      doc.moveDown(1);

      // ── Design Visualization Image ────────────────────────────────

      if (imageBase64) {
        doc.addPage();
        try {
          const rawBase64 = imageBase64.replace(/^data:image\/[a-zA-Z+]+;base64,/, "");
          const imgBuffer = Buffer.from(rawBase64, "base64");
          doc.image(imgBuffer, 50, 60, { width: pageWidth, fit: [pageWidth, 400], align: "center" });
          const imgBottom = doc.y > 60 ? doc.y : 460;
          doc
            .font("Helvetica")
            .fontSize(9)
            .fillColor(COLORS.gray)
            .text("AI-Generated Design Visualization", 50, imgBottom + 10, { width: pageWidth, align: "center" });
          doc.moveDown(1);
        } catch (imgErr) {
          console.error("[generate-garden-pdf] Image embed error:", imgErr.message);
        }
      }

      // ── Report Body ─────────────────────────────────────────────────

      const sections = parseSections(reportMarkdown || "");

      for (const section of sections) {
        // Check if we need a new page (less than 100pt remaining)
        if (doc.y > doc.page.height - 150) {
          doc.addPage();
        }

        if (section.heading) {
          const fontSize = section.level <= 2 ? 14 : 12;
          doc
            .font("Helvetica-Bold")
            .fontSize(fontSize)
            .fillColor(section.level <= 2 ? COLORS.accent : COLORS.darkGray)
            .text(sanitizeText(section.heading));

          doc.moveDown(0.3);
        }

        if (section.body.trim()) {
          // Render body as plain text (tables and formatting stripped)
          const bodyText = stripMd(section.body.trim());
          doc
            .font("Helvetica")
            .fontSize(10)
            .fillColor(COLORS.darkGray)
            .text(sanitizeText(bodyText), { lineGap: 3 });

          doc.moveDown(0.5);
        }
      }

      // ── Sketch Analysis (if available) ──────────────────────────────

      if (sketchAnalysis) {
        if (doc.y > doc.page.height - 200) doc.addPage();

        doc.moveDown(1);
        doc
          .font("Helvetica-Bold")
          .fontSize(14)
          .fillColor(COLORS.accent)
          .text("Sketch Analysis");

        doc.moveDown(0.3);
        doc
          .font("Helvetica")
          .fontSize(9)
          .fillColor(COLORS.gray)
          .text(sanitizeText(sketchAnalysis), { lineGap: 2 });
      }

      // ── Footer on all pages ─────────────────────────────────────────

      const pageCount = doc.bufferedPageRange().count;
      for (let i = 0; i < pageCount; i++) {
        doc.switchToPage(i);
        drawFooter(doc, i + 1);
      }

      // ── Disclaimer ──────────────────────────────────────────────────

      doc.switchToPage(pageCount - 1);
      const disclaimerY = doc.page.height - 80;
      const savedMargin = doc.page.margins.bottom;
      doc.page.margins.bottom = 0;
      doc
        .fontSize(7)
        .font("Helvetica")
        .fillColor(COLORS.lightGray)
        .text(
          "This report is AI-generated and for informational purposes only. It does not constitute professional landscaping, agricultural, or environmental advice. Always consult local experts before implementing changes to your property.",
          50,
          disclaimerY,
          { width: pageWidth, align: "center" }
        );
      doc.page.margins.bottom = savedMargin;

      doc.end();
    } catch (err) {
      reject(err);
    }
  });
}
