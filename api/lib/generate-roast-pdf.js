import PDFDocument from "pdfkit";

const COLORS = {
  black: "#1a1a1a",
  darkGray: "#333333",
  gray: "#666666",
  lightGray: "#999999",
  border: "#e0e0e0",
  accent: "#ff6b35",
  accentDark: "#ff2d55",
  accentLight: "#ffc233",
  high: "#dc2626",
  medium: "#ea580c",
  low: "#ca8a04",
  good: "#16a34a",
  pageBg: "#ffffff",
};

/** Strip characters outside Latin-1 that Helvetica cannot render. */
function sanitizeText(text) {
  if (!text) return "";
  return String(text).replace(/[^\x00-\xFF]/g, "");
}

function getScoreColor(score) {
  if (score <= 3) return COLORS.high;
  if (score <= 5) return COLORS.medium;
  if (score <= 7) return COLORS.low;
  return COLORS.good;
}

function getSeverityColor(severity) {
  const s = (severity || "").toLowerCase();
  if (s === "brutal") return COLORS.accentDark;
  if (s === "harsh") return COLORS.accent;
  if (s === "mild") return COLORS.accentLight;
  if (s === "decent") return COLORS.good;
  if (s === "fire") return "#16a34a";
  return COLORS.accent;
}

function getPriorityColor(priority) {
  const p = (priority || "").toLowerCase();
  if (p === "high") return COLORS.high;
  if (p === "medium") return COLORS.medium;
  return COLORS.low;
}

function drawFooter(doc, pageNum) {
  const y = doc.page.height - 50;
  doc
    .fontSize(7)
    .font("Helvetica")
    .fillColor(COLORS.lightGray)
    .text("Generated by VibeZap.dev — AI Website Analysis", 50, y, {
      align: "center",
      width: doc.page.width - 100,
    })
    .text(
      "This analysis is AI-generated and should not be considered professional advice.",
      50,
      y + 10,
      { align: "center", width: doc.page.width - 100 }
    )
    .text(`Page ${pageNum}`, 50, y + 10, {
      align: "right",
      width: doc.page.width - 100,
    });
}

function drawSectionHeader(doc, title, y) {
  doc
    .fontSize(11)
    .font("Helvetica-Bold")
    .fillColor(COLORS.accent)
    .text(title.toUpperCase(), 50, y);

  doc
    .moveTo(50, y + 16)
    .lineTo(200, y + 16)
    .strokeColor(COLORS.accent)
    .lineWidth(1.5)
    .stroke();

  const nextY = y + 28;
  doc.y = nextY;
  return nextY;
}

function drawWrappedText(doc, text, x, y, options = {}) {
  const {
    fontSize = 9,
    font = "Helvetica",
    color = COLORS.darkGray,
    width = 495,
    lineGap = 3,
  } = options;

  doc.fontSize(fontSize).font(font).fillColor(color);
  doc.text(text, x, y, { width, lineGap });
  return doc.y;
}

function ensureSpace(doc, needed, pageCounter) {
  if (doc.y + needed > doc.page.height - 70) {
    drawFooter(doc, pageCounter.value);
    doc.addPage();
    pageCounter.value++;
    doc.y = 50;
  }
}

export default function generateRoastPdf(data) {
  return new Promise((resolve, reject) => {
    try {
      const doc = new PDFDocument({
        size: "A4",
        margins: { top: 50, bottom: 70, left: 50, right: 50 },
        info: {
          Title: "Website Roast Report — VibeZap.dev",
          Author: "VibeZap.dev",
          Subject: "AI Website Analysis Report",
        },
      });

      const chunks = [];
      doc.on("data", (chunk) => chunks.push(chunk));
      doc.on("end", () => resolve(Buffer.concat(chunks)));
      doc.on("error", reject);

      const pageWidth = doc.page.width - 100;
      const pageCounter = { value: 1 };

      // ── PAGE 1: Cover + Executive Summary ──

      // Brand header
      doc
        .fontSize(9)
        .font("Helvetica-Bold")
        .fillColor(COLORS.accent)
        .text("VIBEZAP.DEV", 50, 50);

      const dateStr = new Date(data.generatedAt || Date.now()).toLocaleString(
        "en-US",
        {
          year: "numeric",
          month: "long",
          day: "numeric",
          hour: "2-digit",
          minute: "2-digit",
          timeZoneName: "short",
        }
      );
      doc
        .fontSize(8)
        .font("Helvetica")
        .fillColor(COLORS.lightGray)
        .text(dateStr, 50, 50, { align: "right", width: pageWidth });

      // Title
      doc
        .fontSize(22)
        .font("Helvetica-Bold")
        .fillColor(COLORS.black)
        .text("WEBSITE ROAST REPORT", 50, 80, {
          align: "center",
          width: pageWidth,
        });

      // Divider
      doc
        .moveTo(50, 110)
        .lineTo(50 + pageWidth, 110)
        .strokeColor(COLORS.border)
        .lineWidth(0.5)
        .stroke();

      // Severity badge
      const sevColor = getSeverityColor(data.severity);
      const sevText = (data.severity || "unknown").toUpperCase();
      const badgeWidth = 160;
      const badgeX = (doc.page.width - badgeWidth) / 2;

      doc.roundedRect(badgeX, 125, badgeWidth, 28, 14);
      doc.fillColor(sevColor).fill();
      doc
        .fontSize(10)
        .font("Helvetica-Bold")
        .fillColor("#ffffff")
        .text(sevText + " ROAST", badgeX, 132, {
          align: "center",
          width: badgeWidth,
        });

      // Overall score
      const scoreColor = getScoreColor(data.overall_score);
      doc
        .fontSize(28)
        .font("Helvetica-Bold")
        .fillColor(scoreColor)
        .text(`${data.overall_score || 0}/10`, 50, 168, {
          align: "center",
          width: pageWidth,
        });
      doc
        .fontSize(9)
        .font("Helvetica")
        .fillColor(COLORS.gray)
        .text("OVERALL SCORE", 50, 198, {
          align: "center",
          width: pageWidth,
        });

      // Roast headline
      doc
        .fontSize(13)
        .font("Helvetica-Bold")
        .fillColor(COLORS.black)
        .text(sanitizeText(data.roast_headline), 50, 220, {
          align: "center",
          width: pageWidth,
        });

      // URL analyzed
      let y = doc.y + 8;
      const urlDisplay = (data.analyzedUrl || "").substring(0, 80);
      doc
        .fontSize(8)
        .font("Helvetica")
        .fillColor(COLORS.lightGray)
        .text(urlDisplay, 50, y, { align: "center", width: pageWidth });

      // Executive summary
      y = doc.y + 16;
      y = drawSectionHeader(doc, "Executive Summary", y);
      y = drawWrappedText(
        doc,
        sanitizeText(data.executive_summary || data.roast_summary),
        50,
        y,
        { fontSize: 10, lineGap: 4 }
      );

      // ── CATEGORY BREAKDOWN ──
      y = doc.y + 20;
      doc.y = y;
      ensureSpace(doc, 300, pageCounter);
      y = doc.y;

      y = drawSectionHeader(doc, "Category Breakdown", y);

      const categories = data.categories || {};
      const catNames = ["Design", "Copy", "UX", "Performance", "Trust"];

      for (const catName of catNames) {
        const cat = categories[catName] || {
          score: 0,
          comment: "",
          detailed_analysis: "",
        };
        const catScore = cat.score || 0;
        const catColor = getScoreColor(catScore);

        ensureSpace(doc, 75, pageCounter);
        y = doc.y;

        // Category name + score
        doc
          .fontSize(10)
          .font("Helvetica-Bold")
          .fillColor(COLORS.black)
          .text(catName, 50, y, { continued: false });

        doc
          .fontSize(10)
          .font("Helvetica-Bold")
          .fillColor(catColor)
          .text(`${catScore}/10`, 50, y, {
            align: "right",
            width: pageWidth,
          });

        y += 16;

        // Score bar
        const barWidth = pageWidth;
        const barHeight = 5;
        doc
          .rect(50, y, barWidth, barHeight)
          .fillColor("#eeeeee")
          .fill();
        doc
          .rect(50, y, barWidth * (catScore / 10), barHeight)
          .fillColor(catColor)
          .fill();

        y += 12;

        // Comment (one-liner)
        if (cat.comment) {
          doc
            .fontSize(9)
            .font("Helvetica-Oblique")
            .fillColor(COLORS.gray)
            .text(`"${sanitizeText(cat.comment)}"`, 50, y, { width: pageWidth });
          y = doc.y + 4;
        }

        // Detailed analysis
        const analysis = sanitizeText(cat.detailed_analysis);
        if (analysis) {
          y = drawWrappedText(doc, analysis, 50, y, {
            fontSize: 9,
            color: COLORS.darkGray,
            lineGap: 2,
          });
        }
        y = doc.y + 14;
      }

      // ── PRIORITY FIXES ──
      y = doc.y + 16;
      doc.y = y;
      ensureSpace(doc, 200, pageCounter);
      y = doc.y;

      y = drawSectionHeader(doc, "Priority Fixes", y);

      const fixes = data.specific_fixes || [];
      const highFixes = fixes.filter(
        (f) => (f.priority || "").toLowerCase() === "high"
      );
      const medFixes = fixes.filter(
        (f) => (f.priority || "").toLowerCase() === "medium"
      );
      const lowFixes = fixes.filter(
        (f) => (f.priority || "").toLowerCase() === "low"
      );

      const fixGroups = [
        { label: "HIGH PRIORITY", fixes: highFixes, color: COLORS.high },
        { label: "MEDIUM PRIORITY", fixes: medFixes, color: COLORS.medium },
        { label: "LOW PRIORITY", fixes: lowFixes, color: COLORS.low },
      ];

      for (const group of fixGroups) {
        if (group.fixes.length === 0) continue;

        ensureSpace(doc, 40, pageCounter);
        y = doc.y;

        // Priority group header
        doc
          .fontSize(9)
          .font("Helvetica-Bold")
          .fillColor(group.color)
          .text(group.label, 50, y);
        doc
          .moveTo(50, doc.y + 3)
          .lineTo(140, doc.y + 3)
          .strokeColor(group.color)
          .lineWidth(1)
          .stroke();
        y = doc.y + 10;
        doc.y = y;

        for (const fix of group.fixes) {
          ensureSpace(doc, 40, pageCounter);
          y = doc.y;

          // Fix title with category tag
          const catTag = fix.category ? ` [${fix.category}]` : "";
          doc
            .fontSize(9)
            .font("Helvetica-Bold")
            .fillColor(COLORS.black)
            .text(`•  ${sanitizeText(fix.title) || "Fix"}`, 56, y, { width: 440 });

          if (catTag) {
            doc
              .fontSize(7)
              .font("Helvetica")
              .fillColor(group.color)
              .text(catTag, 50, y, {
                align: "right",
                width: pageWidth,
              });
          }

          y = doc.y + 2;

          // Fix description
          if (fix.description) {
            y = drawWrappedText(doc, sanitizeText(fix.description), 68, y, {
              fontSize: 8,
              color: COLORS.gray,
              width: 477,
              lineGap: 2,
            });
          }
          y = doc.y + 8;
        }

        y = doc.y + 6;
      }

      // ── QUICK WINS ──
      ensureSpace(doc, 120, pageCounter);
      y = doc.y;
      y = drawSectionHeader(doc, "Quick Wins", y);

      const quickWins = data.quick_wins || [];
      quickWins.forEach((win, i) => {
        ensureSpace(doc, 18, pageCounter);
        y = doc.y;
        y = drawWrappedText(doc, `${i + 1}.  ${sanitizeText(win)}`, 50, y, {
          fontSize: 9,
          color: COLORS.darkGray,
          lineGap: 2,
        });
        y = doc.y + 5;
      });

      // ── COMPETITOR INSIGHTS ──
      const insights = data.competitor_insights || [];
      if (insights.length > 0) {
        y = doc.y + 10;
        ensureSpace(doc, 80, pageCounter);
        y = doc.y;
        y = drawSectionHeader(doc, "Competitor Insights", y);

        for (const insight of insights) {
          ensureSpace(doc, 30, pageCounter);
          y = doc.y;
          doc
            .fontSize(9)
            .font("Helvetica-Bold")
            .fillColor(COLORS.black)
            .text(`•  ${sanitizeText(insight.suggestion)}`, 56, y, { width: 489 });
          y = doc.y + 2;
          if (insight.example) {
            y = drawWrappedText(
              doc,
              `Example: ${sanitizeText(insight.example)}`,
              68,
              y,
              { fontSize: 8, color: COLORS.gray, width: 477 }
            );
          }
          y = doc.y + 8;
        }
      }

      // ── TECHNICAL NOTES ──
      y = doc.y + 16;
      doc.y = y;
      ensureSpace(doc, 200, pageCounter);
      y = doc.y;

      y = drawSectionHeader(doc, "Technical Notes", y);

      if (data.seo_notes) {
        doc
          .fontSize(9)
          .font("Helvetica-Bold")
          .fillColor(COLORS.black)
          .text("SEO Observations", 50, y);
        y = doc.y + 4;
        y = drawWrappedText(doc, sanitizeText(data.seo_notes), 50, y, {
          fontSize: 9,
          color: COLORS.gray,
        });
        y = doc.y + 14;
      }

      if (data.accessibility_notes) {
        ensureSpace(doc, 60, pageCounter);
        y = doc.y;
        doc
          .fontSize(9)
          .font("Helvetica-Bold")
          .fillColor(COLORS.black)
          .text("Accessibility", 50, y);
        y = doc.y + 4;
        y = drawWrappedText(doc, sanitizeText(data.accessibility_notes), 50, y, {
          fontSize: 9,
          color: COLORS.gray,
        });
        y = doc.y + 14;
      }

      if (data.mobile_notes) {
        ensureSpace(doc, 60, pageCounter);
        y = doc.y;
        doc
          .fontSize(9)
          .font("Helvetica-Bold")
          .fillColor(COLORS.black)
          .text("Mobile Experience", 50, y);
        y = doc.y + 4;
        y = drawWrappedText(doc, sanitizeText(data.mobile_notes), 50, y, {
          fontSize: 9,
          color: COLORS.gray,
        });
      }

      // Final footer
      drawFooter(doc, pageCounter.value);

      doc.end();
    } catch (err) {
      reject(err);
    }
  });
}
