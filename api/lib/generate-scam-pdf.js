import PDFDocument from "pdfkit";

const COLORS = {
  black: "#1a1a1a",
  darkGray: "#333333",
  gray: "#666666",
  lightGray: "#999999",
  border: "#e0e0e0",
  accent: "#0891b2", // cyan-600
  safe: "#16a34a",
  suspicious: "#ca8a04",
  likelyScam: "#ea580c",
  definiteScam: "#dc2626",
  pageBg: "#ffffff",
};

function getVerdictColor(verdict) {
  const v = (verdict || "").toLowerCase();
  if (v === "safe") return COLORS.safe;
  if (v === "suspicious") return COLORS.suspicious;
  if (v === "likely scam") return COLORS.likelyScam;
  return COLORS.definiteScam;
}

function getScoreColor(score) {
  if (score <= 3) return COLORS.safe;
  if (score <= 5) return COLORS.suspicious;
  if (score <= 7) return COLORS.likelyScam;
  return COLORS.definiteScam;
}

function drawFooter(doc, pageNum) {
  const y = doc.page.height - 50;
  // Temporarily remove bottom margin so PDFKit doesn't trigger
  // automatic page breaks when drawing below the content area
  const savedMargin = doc.page.margins.bottom;
  doc.page.margins.bottom = 0;

  doc
    .fontSize(7)
    .font("Helvetica")
    .fillColor(COLORS.gray)
    .text("Generated by vibezap.dev/scam-check — AI Scam Detection", 50, y, {
      align: "center",
      width: doc.page.width - 100,
      lineBreak: false,
    })
    .text(
      "This analysis is AI-generated and should not be considered legal advice.",
      50,
      y + 10,
      { align: "center", width: doc.page.width - 100, lineBreak: false }
    )
    .text(`Page ${pageNum}`, 50, y + 10, {
      align: "right",
      width: doc.page.width - 100,
      lineBreak: false,
    });

  doc.page.margins.bottom = savedMargin;
}

function drawSectionHeader(doc, title, y) {
  doc
    .fontSize(11)
    .font("Helvetica-Bold")
    .fillColor(COLORS.accent)
    .text(title.toUpperCase(), 50, y);

  doc.save();
  doc
    .moveTo(50, y + 16)
    .lineTo(200, y + 16)
    .strokeColor(COLORS.accent)
    .lineWidth(1.5)
    .stroke();
  doc.restore();

  return y + 32;
}

function drawWrappedText(doc, text, x, y, options = {}) {
  const {
    fontSize = 9,
    font = "Helvetica",
    color = COLORS.darkGray,
    width = 495,
    lineGap = 3,
  } = options;

  doc.fontSize(fontSize).font(font).fillColor(color);
  doc.text(text, x, y, { width, lineGap });
  return doc.y;
}

function ensureSpace(doc, needed, pageCounter) {
  if (doc.y + needed > doc.page.height - 70) {
    drawFooter(doc, pageCounter.value);
    doc.addPage();
    pageCounter.value++;
    doc.y = 50;
  }
}

export default function generateScamPdf(data) {
  return new Promise((resolve, reject) => {
    try {
      const doc = new PDFDocument({
        size: "A4",
        margins: { top: 50, bottom: 70, left: 50, right: 50 },
        info: {
          Title: "Scam Forensic Report — VibeZap.dev",
          Author: "VibeZap.dev",
          Subject: "AI Scam Analysis Report",
        },
      });

      const chunks = [];
      doc.on("data", (chunk) => chunks.push(chunk));
      doc.on("end", () => resolve(Buffer.concat(chunks)));
      doc.on("error", reject);

      const pageWidth = doc.page.width - 100;
      const pageCounter = { value: 1 };

      // ── PAGE 1: Cover + Executive Summary ──

      // Brand header
      doc
        .fontSize(9)
        .font("Helvetica-Bold")
        .fillColor(COLORS.accent)
        .text("VIBEZAP.DEV", 50, 50);

      const dateStr = new Date(data.generatedAt || Date.now()).toLocaleString(
        "en-US",
        {
          year: "numeric",
          month: "long",
          day: "numeric",
          hour: "2-digit",
          minute: "2-digit",
          timeZoneName: "short",
        }
      );
      doc
        .fontSize(8)
        .font("Helvetica")
        .fillColor(COLORS.lightGray)
        .text(dateStr, 50, 50, { align: "right", width: pageWidth });

      // Title
      doc
        .fontSize(22)
        .font("Helvetica-Bold")
        .fillColor(COLORS.black)
        .text("SCAM FORENSIC REPORT", 50, 80, {
          align: "center",
          width: pageWidth,
        });

      // Divider
      doc.save();
      doc
        .moveTo(50, 110)
        .lineTo(50 + pageWidth, 110)
        .strokeColor(COLORS.border)
        .lineWidth(0.5)
        .stroke();
      doc.restore();

      // Verdict badge
      const verdictColor = getVerdictColor(data.verdict);
      const verdictText = (data.verdict || "Unknown").toUpperCase();
      const badgeWidth = 180;
      const badgeX = (doc.page.width - badgeWidth) / 2;

      doc.roundedRect(badgeX, 125, badgeWidth, 30, 15);
      doc.fillColor(verdictColor).fill();
      doc
        .fontSize(11)
        .font("Helvetica-Bold")
        .fillColor("#ffffff")
        .text(verdictText, badgeX, 133, {
          align: "center",
          width: badgeWidth,
        });

      // Risk score
      const scoreColor = getScoreColor(data.risk_score);
      doc
        .fontSize(28)
        .font("Helvetica-Bold")
        .fillColor(scoreColor)
        .text(`${data.risk_score}/10`, 50, 170, {
          align: "center",
          width: pageWidth,
        });
      doc
        .fontSize(9)
        .font("Helvetica")
        .fillColor(COLORS.gray)
        .text("RISK SCORE", 50, 200, {
          align: "center",
          width: pageWidth,
        });

      // Verdict headline
      doc
        .fontSize(13)
        .font("Helvetica-Bold")
        .fillColor(COLORS.black)
        .text(data.verdict_headline || "", 50, 225, {
          align: "center",
          width: pageWidth,
        });

      // Executive summary
      let y = 260;
      y = drawSectionHeader(doc, "Executive Summary", y);
      y = drawWrappedText(
        doc,
        data.executive_summary || data.summary || "",
        50,
        y,
        { fontSize: 10, lineGap: 4 }
      );

      // Original message excerpt
      y = doc.y + 20;
      ensureSpace(doc, 100, pageCounter);
      y = doc.y > 50 ? doc.y : y;

      y = drawSectionHeader(doc, "Original Message", y);
      const msgExcerpt = (data.originalMessage || "").substring(0, 500);
      const msgDisplay =
        msgExcerpt.length < (data.originalMessage || "").length
          ? msgExcerpt + "..."
          : msgExcerpt;

      // Gray box for original message
      doc.rect(50, y, pageWidth, 10); // placeholder height, will adjust
      doc
        .fontSize(8)
        .font("Helvetica")
        .fillColor(COLORS.gray);
      const msgHeight = doc.heightOfString(msgDisplay, {
        width: pageWidth - 20,
      });
      doc
        .rect(50, y, pageWidth, msgHeight + 16)
        .fillColor("#f5f5f5")
        .fill();
      doc
        .fillColor(COLORS.gray)
        .text(`"${msgDisplay}"`, 60, y + 8, {
          width: pageWidth - 20,
          lineGap: 2,
        });
      y = doc.y + 20;

      // ── PAGE 2: Red Flag Analysis ──
      ensureSpace(doc, 300, pageCounter);
      if (doc.y > 600) {
        drawFooter(doc, pageCounter.value);
        doc.addPage();
        pageCounter.value++;
        y = 50;
      } else {
        y = doc.y;
      }

      y = drawSectionHeader(doc, "Red Flag Analysis", y);

      const categories = data.categories || {};
      const catNames = [
        "Urgency Tactics",
        "Identity Spoofing",
        "Suspicious Links",
        "Grammar Red Flags",
        "Financial Bait",
        "Emotional Manipulation",
      ];

      for (const catName of catNames) {
        const cat = categories[catName] || { score: 0, detailed_analysis: "" };
        const catScore = cat.score || 0;
        const catColor = getScoreColor(catScore);

        ensureSpace(doc, 65, pageCounter);
        y = doc.y;

        // Category name + score
        doc
          .fontSize(10)
          .font("Helvetica-Bold")
          .fillColor(COLORS.black)
          .text(catName, 50, y, { continued: false });

        doc
          .fontSize(10)
          .font("Helvetica-Bold")
          .fillColor(catColor)
          .text(`${catScore}/10`, 50, y, {
            align: "right",
            width: pageWidth,
          });

        y += 16;

        // Score bar
        const barWidth = pageWidth;
        const barHeight = 5;
        doc.save();
        doc
          .rect(50, y, barWidth, barHeight)
          .fillColor("#eeeeee")
          .fill();
        doc
          .rect(50, y, barWidth * (catScore / 10), barHeight)
          .fillColor(catColor)
          .fill();
        doc.restore();

        y += 14;

        // Detailed analysis
        const analysis =
          cat.detailed_analysis || cat.comment || "No issues detected.";
        y = drawWrappedText(doc, analysis, 50, y, {
          fontSize: 9,
          color: COLORS.gray,
          lineGap: 2,
        });
        y = doc.y + 20;
      }

      // ── PAGE 3: Forensic Details ──
      drawFooter(doc, pageCounter.value);
      doc.addPage();
      pageCounter.value++;
      y = 50;

      // Technical indicators
      const tech = data.technical_indicators || {};

      y = drawSectionHeader(doc, "Technical Indicators", y);

      if (tech.url_analysis) {
        doc
          .fontSize(9)
          .font("Helvetica-Bold")
          .fillColor(COLORS.black)
          .text("URL & Link Analysis", 50, y);
        y = doc.y + 8;
        y = drawWrappedText(doc, tech.url_analysis, 50, y, {
          fontSize: 9,
          color: COLORS.gray,
        });
        y = doc.y + 14;
      }

      if (tech.language_patterns) {
        ensureSpace(doc, 60, pageCounter);
        y = doc.y;
        doc
          .fontSize(9)
          .font("Helvetica-Bold")
          .fillColor(COLORS.black)
          .text("Language Pattern Analysis", 50, y);
        y = doc.y + 8;
        y = drawWrappedText(doc, tech.language_patterns, 50, y, {
          fontSize: 9,
          color: COLORS.gray,
        });
        y = doc.y + 14;
      }

      if (tech.social_engineering?.length) {
        ensureSpace(doc, 60, pageCounter);
        y = doc.y;
        doc
          .fontSize(9)
          .font("Helvetica-Bold")
          .fillColor(COLORS.black)
          .text("Social Engineering Techniques", 50, y);
        y = doc.y + 4;
        for (const technique of tech.social_engineering) {
          ensureSpace(doc, 16, pageCounter);
          y = doc.y;
          y = drawWrappedText(doc, `•  ${technique}`, 56, y, {
            fontSize: 9,
            color: COLORS.gray,
            width: 489,
          });
          y = doc.y + 6;
        }
        y = doc.y + 10;
      }

      // Immediate actions (risk-specific)
      if (data.immediate_actions?.length) {
        ensureSpace(doc, 80, pageCounter);
        y = doc.y;
        y = drawSectionHeader(doc, "Immediate Actions", y);
        for (const item of data.immediate_actions) {
          ensureSpace(doc, 40, pageCounter);
          y = doc.y;
          const priority = (item.priority || "").toUpperCase();
          const priorityColor =
            priority === "HIGH"
              ? COLORS.definiteScam
              : priority === "MEDIUM"
                ? COLORS.suspicious
                : COLORS.safe;

          // Priority badge
          const badgeText = priority || "ACTION";
          const badgeW = doc
            .fontSize(7)
            .font("Helvetica-Bold")
            .widthOfString(badgeText) + 10;
          doc.save();
          doc
            .roundedRect(50, y, badgeW, 14, 3)
            .fillColor(priorityColor)
            .fill();
          doc.restore();
          doc
            .fontSize(7)
            .font("Helvetica-Bold")
            .fillColor("#ffffff")
            .text(badgeText, 55, y + 3, { lineBreak: false });

          // Action text
          y += 20;
          y = drawWrappedText(doc, item.action || "", 50, y, {
            fontSize: 9,
            font: "Helvetica-Bold",
            color: COLORS.black,
          });
          if (item.reason) {
            y = doc.y + 2;
            y = drawWrappedText(doc, item.reason, 50, y, {
              fontSize: 8,
              color: COLORS.gray,
            });
          }
          y = doc.y + 12;
        }
        y = doc.y + 6;
      }

      // Similar scam patterns
      if (data.similar_scam_patterns?.length) {
        ensureSpace(doc, 60, pageCounter);
        y = doc.y;
        y = drawSectionHeader(doc, "Similar Known Scam Patterns", y);
        for (const pattern of data.similar_scam_patterns) {
          ensureSpace(doc, 20, pageCounter);
          y = doc.y;
          y = drawWrappedText(doc, `•  ${pattern}`, 56, y, {
            fontSize: 9,
            color: COLORS.gray,
            width: 489,
          });
          y = doc.y + 6;
        }
        y = doc.y + 10;
      }

      // How to report
      if (data.how_to_report?.length) {
        ensureSpace(doc, 80, pageCounter);
        y = doc.y;
        y = drawSectionHeader(doc, "How to Report This", y);
        for (const report of data.how_to_report) {
          ensureSpace(doc, 30, pageCounter);
          y = doc.y;
          const authority = report.authority || "Authority";
          const url = report.url ? ` (${report.url})` : "";
          doc
            .fontSize(9)
            .font("Helvetica-Bold")
            .fillColor(COLORS.accent)
            .text(`${authority}${url}`, 50, y);
          y = doc.y + 4;
          y = drawWrappedText(doc, report.description || "", 50, y, {
            fontSize: 9,
            color: COLORS.gray,
          });
          y = doc.y + 12;
        }
      }

      // Protection tips
      if (data.protection_tips?.length) {
        ensureSpace(doc, 80, pageCounter);
        y = doc.y;
        y = drawSectionHeader(doc, "Protection Tips", y);
        data.protection_tips.forEach((tip, i) => {
          ensureSpace(doc, 16, pageCounter);
          y = doc.y;
          y = drawWrappedText(doc, `${i + 1}.  ${tip}`, 50, y, {
            fontSize: 9,
            color: COLORS.darkGray,
            lineGap: 2,
          });
          y = doc.y + 8;
        });
      }

      // Final footer
      drawFooter(doc, pageCounter.value);

      doc.end();
    } catch (err) {
      reject(err);
    }
  });
}
