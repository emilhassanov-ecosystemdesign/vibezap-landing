export async function sendReportEmail({
  to,
  userName,
  subject,
  reportType,
  reportData,
  pdfBuffer,
  pdfFilename,
  resendApiKey,
}) {
  if (!resendApiKey || !to) {
    return { sent: false, error: "Email not configured" };
  }

  try {
    let htmlBody;
    if (reportType === "roast") {
      htmlBody = roastEmailHtml({
        userName,
        url: reportData.analyzedUrl || "your website",
        score: reportData.overall_score,
        severity: reportData.severity,
        headline: reportData.roast_headline,
      });
    } else if (reportType === "land") {
      htmlBody = landEmailHtml({
        userName,
        locationName: reportData.location?.displayName?.split(",")[0] || "Your Property",
      });
    } else {
      htmlBody = scamEmailHtml({
        userName,
        verdict: reportData.verdict,
        riskScore: reportData.risk_score,
        headline: reportData.verdict_headline,
      });
    }

    const response = await fetch("https://api.resend.com/emails", {
      method: "POST",
      headers: {
        Authorization: `Bearer ${resendApiKey}`,
        "Content-Type": "application/json",
      },
      body: JSON.stringify({
        from: "VibeZap Reports <reports@vibezap.dev>",
        to: [to],
        subject,
        html: htmlBody,
        attachments: [
          {
            filename: pdfFilename,
            content: pdfBuffer.toString("base64"),
          },
        ],
      }),
    });

    if (!response.ok) {
      const err = await response.json().catch(() => ({}));
      console.error("Resend API error:", err);
      return { sent: false, error: err.message || "Email send failed" };
    }

    return { sent: true };
  } catch (err) {
    console.error("Email send error:", err);
    return { sent: false, error: err.message };
  }
}
